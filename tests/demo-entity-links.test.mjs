test('same-tenant client links CRM opportunity, Agenda and Expedientes; 360 view uses IDs not text',async()=>{
 const store=createDemoStore(catalog);
 const [a,b]=(await store.request('/api/app/organizations')).organizations;
 const client=(await store.request('/api/app/'+a.slug+'/workflows/clients')).clients[0];
 const foreign=(await store.request('/api/app/'+b.slug+'/workflows/clients')).clients[0];
 const crm='/api/app/'+a.slug+'/workflows/crm';
 await assert.rejects(()=>store.request(crm,{method:'POST',body:JSON.stringify({title:'Cruce prohibido',clientId:foreign.id})}),/Client not found/);
 const deal=await store.request(crm,{method:'POST',body:JSON.stringify({title:'Contrato norte',customer:'Texto antiguo',clientId:client.id,amountCents:120000,stage:'proposal'})});
 const created=deal.deal;
 assert.equal((await store.request(crm)).deals.find(x=>x.id===created.id).clientId,client.id);
 const agenda='/api/app/'+a.slug+'/workflows/agenda';
 const appointment=await store.request(agenda,{method:'POST',body:JSON.stringify({title:'Revisión',resource:'sala-2',startsAt:'2026-12-01T12:00:00.000Z',endsAt:'2026-12-01T13:00:00.000Z',dealId:created.id})});
 assert.equal(appointment.event.clientId,client.id);
 await assert.rejects(()=>store.request(agenda,{method:'POST',body:JSON.stringify({title:'Otra reunión',resource:'sala-3',startsAt:'2026-12-01T12:00:00.000Z',endsAt:'2026-12-01T13:00:00.000Z',dealId:created.id,clientId:foreign.id})}),/Relation mismatch/);
 const summary=await store.request('/api/app/'+a.slug+'/workflows/clients/'+client.id+'/summary');
 assert.ok(summary.deals.some(x=>x.id===created.id));
 assert.ok(summary.appointments.some(x=>x.id===appointment.event.id));
 assert.ok(summary.cases.length>0);
 const clientBefore=(await store.request('/api/app/'+a.slug+'/workflows/clients')).clients.find(x=>x.id===client.id);
 await store.request('/api/app/'+a.slug+'/workflows/clients/'+client.id,{method:'PATCH',body:JSON.stringify({...clientBefore,name:'Nuevo nombre'})});
 const after=await store.request('/api/app/'+a.slug+'/workflows/clients/'+client.id+'/summary');
 assert.equal(after.client.name,'Nuevo nombre');
 assert.ok(after.deals.some(x=>x.id===created.id));
});
test('generic T and C Tools can link real records safely, dedupe bidirectionally and follow permissions',async()=>{
 const store=createDemoStore(catalog);
 const [a,b]=(await store.request('/api/app/organizations')).organizations;
 const client=(await store.request('/api/app/'+a.slug+'/workflows/clients')).clients[0];
 const clientB=(await store.request('/api/app/'+b.slug+'/workflows/clients')).clients[0];
 const generic='/api/app/'+a.slug+'/tools/T004/records';
 const task=(await store.request(generic,{method:'POST',body:JSON.stringify({title:'Visitar prospecto',status:'active',fields:{responsable:'Equipo'}})})).record;
 const path=generic+'/'+task.id+'/links';
 const relation=await store.request(path,{method:'POST',body:JSON.stringify({targetToolId:'C001',targetRecordId:client.id})});
 assert.ok(relation.link.id);
 let links=(await store.request(path)).links;
 assert.equal(links.length,1);assert.equal(links[0].targetToolId,'C001');
 const reverse=(await store.request('/api/app/'+a.slug+'/tools/C001/records/'+client.id+'/links')).links;
 assert.ok(reverse.some(x=>x.targetRecordId===task.id));
 await assert.rejects(()=>store.request('/api/app/'+a.slug+'/tools/C001/records/'+client.id+'/links',{method:'POST',body:JSON.stringify({targetToolId:'T004',targetRecordId:task.id})}),/Duplicate relation/);
 await assert.rejects(()=>store.request(path,{method:'POST',body:JSON.stringify({targetToolId:'C001',targetRecordId:clientB.id})}),/Not found/);
 await store.request('/api/app/'+a.slug+'/relations/'+relation.link.id,{method:'DELETE'});
 assert.equal((await store.request(path)).links.length,0);
});
test('Core relationships appear automatically in both directions without manual links',async()=>{
 const store=createDemoStore(catalog);
 const a=(await store.request('/api/app/organizations')).organizations[0];
 const client=(await store.request('/api/app/'+a.slug+'/workflows/clients')).clients[0];
 const core=(await store.request('/api/app/'+a.slug+'/tools/C001/records/'+client.id+'/links')).links;
 const codes=new Set(core.filter(x=>x.builtIn).map(x=>x.targetToolId));
 assert.ok(codes.has('C002'));assert.ok(codes.has('C003'));assert.ok(codes.has('C004'));
 const deal=core.find(x=>x.targetToolId==='C002');
 const reverse=(await store.request('/api/app/'+a.slug+'/tools/C002/records/'+deal.targetRecordId+'/links')).links;
 assert.ok(reverse.some(x=>x.builtIn&&x.targetToolId==='C001'&&x.targetRecordId===client.id));
 const dossier=core.find(x=>x.targetToolId==='C003');
 const file=(await store.request('/api/app/'+a.slug+'/tools/C003/records/'+dossier.targetRecordId+'/links')).links;
 assert.ok(file.some(x=>x.builtIn&&x.targetToolId==='C001'&&x.targetRecordId===client.id));
});
