import test from 'node:test';import assert from 'node:assert/strict';
import {createDemoStore} from '../assets/demo-backend.js';
import {catalog} from '../platform/catalog.mjs';
const file={filename:'contrato.pdf',mime:'application/pdf',data:Buffer.from('%PDF-1.4\nFactura').toString('base64')};
test('case documents have types, expiry and readable revisions, scoped to their tenant',async()=>{
 const store=createDemoStore(catalog);
 const [a,b]=(await store.request('/api/app/organizations')).organizations;
 const caseA=(await store.request('/api/app/'+a.slug+'/workflows/cases')).cases[0];
 const base='/api/app/'+a.slug+'/tools/C003/records/'+caseA.id+'/attachments';
 const v1=await store.request(base,{method:'POST',body:JSON.stringify({...file,documentType:'contract',expiresOn:'2027-06-30'})});
 let result=await store.request(base);let first=result.attachments.find(x=>x.id===v1.attachment.id);
 assert.equal(first.documentType,'contract');assert.equal(first.expiresOn,'2027-06-30');
 assert.equal(first.version,1);assert.equal(first.isLatest,true);
 const changedPayload=Buffer.from('%PDF-1.4\\nVersion 2 modificada').toString('base64');
 const v2=await store.request(base,{method:'POST',body:JSON.stringify({...file,data:changedPayload,replaceDocumentId:first.documentId})});
 result=await store.request(base);
 const old=result.attachments.find(x=>x.id===first.id),latest=result.attachments.find(x=>x.id===v2.attachment.id);
 assert.equal(old.isLatest,false);assert.equal(latest.version,2);assert.equal(latest.isLatest,true);
 assert.equal(latest.documentId,first.documentId);assert.equal(latest.documentType,'contract');
 assert.equal(latest.expiresOn,'2027-06-30');
 const originalData=(await store.request(old.downloadUrl)).file.data;
 const updatedData=(await store.request(latest.downloadUrl)).file.data;
 assert.equal(originalData,file.data,'version 1 bytes remain unchanged');
 assert.equal(updatedData,changedPayload,'version 2 stores different bytes');
 assert.notEqual(originalData,updatedData);

 const metadataRoute='/api/app/'+a.slug+'/case-documents/'+first.documentId;
 await store.request(metadataRoute,{method:'PATCH',body:JSON.stringify({documentType:'identification',expiresOn:'2027-12-31'})});
 result=await store.request(base);
 assert.equal(result.attachments.find(x=>x.id===latest.id).documentType,'identification');
 assert.equal((await store.request('/api/app/'+b.slug+'/workflows/cases')).cases.some(x=>x.id===caseA.id),false);
 await assert.rejects(()=>store.request('/api/app/'+b.slug+'/case-documents/'+first.documentId,{method:'PATCH',body:JSON.stringify({documentType:'other'})}),/Not found/);
 assert.ok((await store.request('/api/app/'+a.slug+'/workflows/cases/'+caseA.id+'/history')).events.some(x=>x.action==='updated'&&x.description.includes('Documento actualizado')));
});
test('legacy unclassified C003 attachment is adopted as v1 without destroying its bytes',async()=>{
 let snapshot;
 const store=createDemoStore(catalog,{save:state=>snapshot=state});
 const org=(await store.request('/api/app/organizations')).organizations[0];
 const dossier=(await store.request('/api/app/'+org.slug+'/workflows/cases')).cases[0];
 const base='/api/app/'+org.slug+'/tools/C003/records/'+dossier.id+'/attachments';
 const old=await store.request(base,{method:'POST',body:JSON.stringify(file)});
 const tenant=snapshot.tenants.find(x=>x.slug===org.slug);
 delete tenant.caseDocumentMeta[old.attachment.documentId];
 const media=tenant.uploads.find(x=>x.id===old.attachment.id);
 delete media.documentId;delete media.version;
 const reopened=createDemoStore(catalog,{load:()=>snapshot});
 const previous=(await reopened.request(base)).attachments.find(x=>x.id===old.attachment.id);
 assert.equal(previous.managed,false);
 const revised=await reopened.request(base,{method:'POST',body:JSON.stringify({...file,replaceDocumentId:old.attachment.id})});
 const items=(await reopened.request(base)).attachments.filter(x=>x.documentId===old.attachment.id);
 assert.deepEqual(items.map(x=>x.version).sort(),[1,2]);
 assert.equal(items.find(x=>x.id===old.attachment.id).isLatest,false);
 assert.equal(items.find(x=>x.id===revised.attachment.id).isLatest,true);
 assert.equal((await reopened.request(previous.downloadUrl)).file.data,file.data);
});
